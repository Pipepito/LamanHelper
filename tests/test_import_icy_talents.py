"""Unit tests for tools/import_icy_talents.py (the transform step, no network).

Run: python -m unittest tests/test_import_icy_talents.py -v
"""
import os
import sys
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))

import import_icy_talents as it  # noqa: E402

INDEX = {"product": "wowf", "latest": "3-c", "versions": [
    {"version": "1-a", "created": "2026-11-01", "layoutChanged": True},
    {"version": "2-b", "created": "2026-11-10", "layoutChanged": True},
    {"version": "3-c", "created": "2026-11-17", "layoutChanged": False},
]}
PRIEST = {"class": "Priest", "slug": "priest", "classId": 5, "talentGroups": [
    {"name": "Discipline", "slug": "discipline", "talents": [
        {"name": "Power in Light", "nodeId": 101, "urlId": "0", "maxRank": 5, "ranks": [{"id": 1309969}, {"id": 1309970}]},
        None]},
    {"name": "Shadow", "slug": "shadow", "talents": [
        {"name": "Spirit Tap", "nodeId": 301, "urlId": "B", "maxRank": 5, "ranks": [{"id": 15270}]}]},
]}


class T(unittest.TestCase):
    def test_compatible_versions_back_to_last_layout_change(self):
        self.assertEqual(it.compatible_versions(INDEX), ["3-c", "2-b"])

    def test_transform_lua(self):
        lua = it.transform(INDEX, {"priest": PRIEST}, date="d")
        self.assertIn('version = "3-c"', lua)
        self.assertIn('["2-b"] = true', lua)
        self.assertNotIn('["1-a"]', lua)
        self.assertIn('PRIEST = {', lua)
        self.assertIn('["0"] = { node = 101, spell = 1309969, maxRank = 5 }', lua)
        self.assertIn('["B"] = { node = 301, spell = 15270, maxRank = 5 }', lua)
        self.assertTrue(lua.startswith("-- Generated by tools/import_icy_talents.py"))
        self.assertIn("icy-veins.com", lua)

    def test_deterministic(self):
        self.assertEqual(it.transform(INDEX, {"priest": PRIEST}, date="d"), it.transform(INDEX, {"priest": PRIEST}, date="d"))


if __name__ == "__main__":
    unittest.main()
