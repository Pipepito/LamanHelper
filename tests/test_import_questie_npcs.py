def kinds_of(out, npc_id):
    return sorted(k for k, ids in out["kinds"].items() if npc_id in ids)


class Classify(unittest.TestCase):
    def setUp(self):
        self.out = iq.extract(NPC_DB, CONVERSION)

    def test_innkeeper(self):
        self.assertEqual(kinds_of(self.out, 295), ["inn"])

    def test_repair_flag(self):
        self.assertEqual(kinds_of(self.out, 1001), ["repair"])

    def test_supplies_titles(self):
        self.assertEqual(kinds_of(self.out, 1002), ["supplies"])
        self.assertEqual(kinds_of(self.out, 1003), ["supplies"])

    def test_class_trainer(self):
        self.assertEqual(kinds_of(self.out, 1006), ["trainer_MAGE"])

    def test_weapon_master(self):
        self.assertEqual(kinds_of(self.out, 11867), ["weapon"])

    def test_profession_trainers_by_word(self):
        self.assertEqual(kinds_of(self.out, 1008), ["prof_182"])  # Herbalist with the trainer flag
        self.assertEqual(kinds_of(self.out, 1011), ["prof_129"])  # Physician = First Aid
        self.assertEqual(kinds_of(self.out, 1012), ["prof_197"])  # Journeyman Tailor

    def test_not_a_trainer_without_the_flag(self):
        self.assertEqual(kinds_of(self.out, 1009), [])

    def test_specialization_trainers_skipped(self):
        self.assertEqual(kinds_of(self.out, 1010), [])

    def test_hostile_to_both_dropped(self):
        self.assertNotIn(1004, self.out["npcs"])

    def test_unmapped_area_dropped(self):
        self.assertNotIn(1005, self.out["npcs"])

    def test_npc_fields_and_first_mapped_spawn(self):
        self.assertEqual(self.out["npcs"][295], ("Innkeeper Farley", "Innkeeper", 1429, 43.77, 65.8, "A"))
        self.assertEqual(self.out["npcs"][1003][2], 1429)
        self.assertEqual(self.out["npcs"][1003][5], "AH")


class Render(unittest.TestCase):
    def test_lua_output_is_deterministic_and_attributed(self):
        a = iq.transform(NPC_DB, CONVERSION, commit="abc123", date="2026-11-22")
        b = iq.transform(NPC_DB, CONVERSION, commit="abc123", date="2026-11-22")
        self.assertEqual(a, b)
        self.assertIn("Generated by tools/import_questie_npcs.py on 2026-11-22", a)
        self.assertIn("https://github.com/Questie/QuestieDB (abc123)", a)
        self.assertIn("GPL-3.0", a)
        self.assertIn("NN.ServiceData = {", a)
        self.assertIn('[295] = { "Innkeeper Farley", "Innkeeper", 1429, 43.77, 65.8, "A" },', a)
        self.assertIn("    inn = { 295 },", a)

    def test_lua_output_loads(self):
        import lupa.luajit21 as lupa
        text = iq.transform(NPC_DB, CONVERSION, commit="x", date="d")
        lua = lupa.LuaRuntime()
        ns = lua.eval("{}")
        lua.execute(text.replace("local _, NN = ...", "local NN = ..."), ns)
        self.assertEqual(ns.ServiceData.kinds.repair[1], 1001)
        self.assertEqual(ns.ServiceData.npcs[1006][1], "Jor")


