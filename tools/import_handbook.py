"""Import game data tables from the WoW Handbook addon (GPL-3.0) into NewbieNudge.

Downloads four generated Lua data files from
https://github.com/Arcaneology/WowHandbookAddon, executes them in a Lua
sandbox (lupa, vendored in tools/pylib) and writes trimmed tables to
NewbieNudge/Data/: MapFog.lua, TrainerSpells.lua, Zones.lua, Dungeons.lua.

Usage:
    python tools/import_handbook.py [--ref main] [--out NewbieNudge/Data]

Output is deterministic: re-running against the same upstream commit
produces no diff.
"""
import argparse
import datetime
import json
import os
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools", "pylib"))

try:
    import lupa.luajit21 as lupa
except ImportError:  # pragma: no cover
    import lupa.lua51 as lupa

REPO = "Arcaneology/WowHandbookAddon"
SOURCE_URL = "https://github.com/" + REPO
UPSTREAM = {
    "MapFog": "MapOverlays.lua",
    "TrainerSpells": "Spells.lua",
    "Zones": "Zones.lua",
    "Dungeons": "Dungeons.lua",
}
RACE_TOKENS = {"Night Elf": "NightElf", "Undead": "Scourge"}


# --------------------------------------------------------------------------
# Lua in, Python out
# --------------------------------------------------------------------------

def _to_python(value):
    """Converts a lupa table into dicts/lists; a table keyed exactly 1..n becomes a list."""
    if not lupa.lua_type(value) == "table":
        return value
    items = list(value.items())
    keys = [k for k, _ in items]
    if keys and all(isinstance(k, int) for k in keys) and sorted(keys) == list(range(1, len(keys) + 1)):
        ordered = sorted(items, key=lambda kv: kv[0])
        return [_to_python(v) for _, v in ordered]
    return {k: _to_python(v) for k, v in items}


def load_lua_table(src, field):
    """Executes an upstream data file and returns ns.Data[field] as Python data."""
    lua = lupa.LuaRuntime(unpack_returned_tuples=True)
    run = lua.eval(
        "function(src, field) local ns = {} local chunk = assert(loadstring(src)) "
        "chunk('WowHandbook', ns) return ns.Data and ns.Data[field] end"
    )
    return _to_python(run(src, field))


# --------------------------------------------------------------------------
# Transform
# --------------------------------------------------------------------------

def _header(name, source, commit, date):
    return (
        "-- Generated by tools/import_handbook.py on %s. Do not edit by hand.\n"
        "-- Source: %s (%s), file WowHandbook/Data/%s\n"
        "-- Licence: GPL-3.0, see LICENSE. Data (c) the WoW Handbook authors (Arcaneology/ArcaneStudio).\n"
        "local _, NN = ...\n" % (date, source, commit, UPSTREAM[name])
    )


def _race_token(name):
    return RACE_TOKENS.get(name, name.replace(" ", ""))


def _lua_str(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def _map_fog(table):
    lines = ["NN.MapFog = {"]
    for map_id in sorted(int(k) for k in table):
        lines.append("  [%d] = {" % map_id)
        for row in table[map_id] if map_id in table else table[str(map_id)]:
            lines.append("    { %s }," % ", ".join(str(int(v)) for v in row))
        lines.append("  },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def _trainer_spells(table):
    lines = ["NN.TrainerSpells = {"]
    for class_key in sorted(table):
        entries = []
        for spell_index, spell in enumerate(table[class_key], start=1):
            races = spell.get("races") if isinstance(spell, dict) else None
            # warlock demon abilities: learned by the demon, not the player
            pet = isinstance(spell, dict) and spell.get("pet") is not None
            for rank_index, rank in enumerate(spell.get("ranks") or [], start=1):
                if not isinstance(rank, dict) or rank.get("id") is None or rank.get("level") is None:
                    continue
                entry = "{ level = %d, id = %d, spell = %d, rank = %d" % (
                    int(rank["level"]), int(rank["id"]), spell_index, rank_index)
                if pet:
                    entry += ", pet = true"
                if races:
                    entry += ", races = { %s }" % ", ".join(_lua_str(_race_token(r)) for r in races)
                entries.append(entry + " }")
        lines.append("  %s = {" % class_key.upper())
        for entry in entries:
            lines.append("    %s," % entry)
        lines.append("  },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def _zones(table):
    lines = ["NN.Zones = {"]
    for map_id in sorted(int(k) for k in table):
        zone = table.get(map_id, table.get(str(map_id)))
        levels = zone.get("levels") if isinstance(zone, dict) else None
        if zone.get("kind") != "zone" or not levels or len(levels) < 2:
            continue
        lines.append("  [%d] = { min = %d, max = %d }," % (map_id, int(levels[0]), int(levels[1])))
    lines.append("}")
    return "\n".join(lines) + "\n"


def _dungeons(table):
    rows = []
    for d in table:
        if not isinstance(d, dict) or d.get("aggregateOnly") or d.get("dataPending"):
            continue
        levels = d.get("levels")
        entrance = d.get("entrance") or {}
        if d.get("instanceID") is None or not levels or len(levels) < 2 or entrance.get("map") is None:
            continue
        rows.append({
            "instanceID": int(d["instanceID"]), "min": int(levels[0]), "max": int(levels[1]),
            "faction": d.get("faction"), "mapID": int(entrance["map"]),
            "nameEN": (d.get("name") or {}).get("enUS") or d.get("slug") or "",
            "quests": [int(q) for q in (d.get("quests") or [])],
        })
    rows.sort(key=lambda r: (r["min"], r["nameEN"]))
    lines = ["NN.Dungeons = {"]
    for r in rows:
        faction = (' faction = %s,' % _lua_str(r["faction"])) if r["faction"] else ""
        lines.append("  { instanceID = %d, min = %d, max = %d,%s mapID = %d, nameEN = %s, quests = { %s } }," % (
            r["instanceID"], r["min"], r["max"], faction, r["mapID"], _lua_str(r["nameEN"]),
            ", ".join(str(q) for q in r["quests"])))
    lines.append("}")
    return "\n".join(lines) + "\n"


def transform(tables, source=SOURCE_URL, commit="unknown", date=None):
    """tables: {"spells":..., "zones":..., "dungeons":..., "mapOverlays":...} -> {Name: lua text}."""
    date = date or datetime.date.today().isoformat()
    bodies = {
        "MapFog": _map_fog(tables["mapOverlays"]),
        "TrainerSpells": _trainer_spells(tables["spells"]),
        "Zones": _zones(tables["zones"]),
        "Dungeons": _dungeons(tables["dungeons"]),
    }
    return {name: _header(name, source, commit, date) + body for name, body in bodies.items()}


# --------------------------------------------------------------------------
# Download and write
# --------------------------------------------------------------------------

def _get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "NewbieNudge-import/1.0"})
    with urllib.request.urlopen(req, timeout=60) as resp:
        return resp.read().decode("utf-8")


def resolve_commit(ref):
    data = json.loads(_get("https://api.github.com/repos/%s/commits/%s" % (REPO, ref)))
    return data["sha"]


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ref", default="main", help="branch, tag or commit (default: main)")
    parser.add_argument("--out", default=os.path.join("NewbieNudge", "Data"), help="output folder")
    args = parser.parse_args(argv)

    sha = resolve_commit(args.ref)
    raw = "https://raw.githubusercontent.com/%s/%s/WowHandbook/Data/" % (REPO, sha)
    tables = {
        "mapOverlays": load_lua_table(_get(raw + "MapOverlays.lua"), "mapOverlays"),
        "spells": load_lua_table(_get(raw + "Spells.lua"), "spells"),
        "zones": load_lua_table(_get(raw + "Zones.lua"), "zones"),
        "dungeons": load_lua_table(_get(raw + "Dungeons.lua"), "dungeons"),
    }
    out = transform(tables, commit=sha)
    os.makedirs(args.out, exist_ok=True)
    for name, text in out.items():
        path = os.path.join(args.out, name + ".lua")
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote", path)
    print("source commit", sha)
    return 0


if __name__ == "__main__":
    sys.exit(main())
