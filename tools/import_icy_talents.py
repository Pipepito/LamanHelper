"""Import Icy Veins' Forever talent identifiers into NewbieNudge.

Downloads the public talent data the Icy Veins talent calculator uses
(static JSON, one file per class) and writes NewbieNudge/Data/IcyTalents.lua
with, per class, the mapping from the calculator link's one-character talent
ids (urlId) to the in-game trait node id, the rank-1 spell id and the max
rank. Only identifiers are kept; talent data (c) Icy Veins (Vedatis S.A.S.).

Usage:
    python tools/import_icy_talents.py [--out NewbieNudge/Data/IcyTalents.lua]
"""
import argparse
import datetime
import json
import os
import sys
import urllib.request

BASE = "https://static.icy-veins.com/r2/icydb/wowf/talents"
CLASSES = ["warrior", "paladin", "hunter", "rogue", "priest", "shaman", "mage", "warlock", "druid"]


def _get_json(url):
    req = urllib.request.Request(url, headers={"User-Agent": "NewbieNudge-import/1.0"})
    with urllib.request.urlopen(req, timeout=60) as resp:
        return json.loads(resp.read().decode("utf-8"))


def compatible_versions(index):
    """Versions whose urlIds match the latest: newest first, back to and
    including the most recent one that changed the layout."""
    versions = sorted(index.get("versions", []), key=lambda v: v.get("created", ""), reverse=True)
    out = []
    for v in versions:
        out.append(v["version"])
        if v.get("layoutChanged"):
            break
    return out


def transform(index, class_jsons, date=None):
    date = date or datetime.date.today().isoformat()
    latest = index["latest"]
    compat = compatible_versions(index)
    lines = [
        "-- Generated by tools/import_icy_talents.py on %s. Do not edit by hand." % date,
        "-- Source: %s/index.json and <version>/<class>.json (version %s)" % (BASE, latest),
        "-- Identifiers only (talent urlId -> in-game node, rank-1 spell, max rank);",
        "-- talent data (c) Icy Veins (Vedatis S.A.S.), https://www.icy-veins.com/",
        "local _, NN = ...",
        "NN.IcyTalents = {",
        '  version = "%s",' % latest,
        "  compatible = { %s }," % ", ".join('["%s"] = true' % v for v in compat),
    ]
    for slug in sorted(class_jsons):
        data = class_jsons[slug]
        entries = {}
        for group in data.get("talentGroups", []):
            for talent in group.get("talents", []) or []:
                if not isinstance(talent, dict):
                    continue
                url_id, node = talent.get("urlId"), talent.get("nodeId")
                if url_id is None or node is None:
                    continue
                ranks = talent.get("ranks") or []
                spell = (ranks[0] or {}).get("id", 0) if ranks else 0
                entries[str(url_id)] = (int(node), int(spell or 0), int(talent.get("maxRank") or len(ranks) or 1))
        lines.append("  %s = {" % slug.upper())
        for url_id in sorted(entries):
            node, spell, max_rank = entries[url_id]
            lines.append('    ["%s"] = { node = %d, spell = %d, maxRank = %d },' % (url_id, node, spell, max_rank))
        lines.append("  },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default=os.path.join("NewbieNudge", "Data", "IcyTalents.lua"))
    args = parser.parse_args(argv)
    index = _get_json(BASE + "/index.json")
    latest = index["latest"]
    class_jsons = {slug: _get_json("%s/%s/%s.json" % (BASE, latest, slug)) for slug in CLASSES}
    text = transform(index, class_jsons)
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", args.out, "version", latest)
    return 0


if __name__ == "__main__":
    sys.exit(main())
